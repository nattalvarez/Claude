"""Builds src/data/timing.json (scenes, cuts, music sections, SFX cues) from the Scribe word timestamps.
Single source of truth for the visuals (src/timing.ts mirrors the same word lookup) and for gen-audio.py."""
import json, re, unicodedata, pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
OFFSET = 1.2
words = json.loads((ROOT / "src/data/words.json").read_text())

def norm(s):
    s = unicodedata.normalize("NFD", s.lower())
    s = "".join(c for c in s if unicodedata.category(c) != "Mn")
    return re.sub(r"[^a-z0-9+]", "", s)

for w in words:
    w["n"] = norm(w["text"])

def idx(text, nth=0):
    seen = 0
    for i, w in enumerate(words):
        if w["n"] == norm(text):
            if seen == nth:
                return i
            seen += 1
    raise KeyError(f"{text}#{nth}")

def vw(text, nth=0, rel=0):
    return round(words[idx(text, nth) + rel]["start"] + OFFSET, 3)

def vwe(text, nth=0, rel=0):
    return round(words[idx(text, nth) + rel]["end"] + OFFSET, 3)

VO_END = round(words[-1]["end"] + OFFSET, 3)

# cuts sit inside the natural gaps between sentences (±0.16 s), on the 8th-note grid of 120 BPM
CUTS = [3.5, 9.5, 15.0, 20.5, 28.75, 31.5, 39.0]
names = ["Hook", "Atmira / banca y seguros", "Cifras", "Presencia internacional (mapa)", "SIREC + Agent Fabric (escena clara)",
         "Potencia / Integra / Orquesta", "Consultoria", "Cierre / logo Atmira"]
bounds = [0.0] + CUTS + [48.0]
scenes = {f"s{i+1}": {"start": bounds[i], "end": bounds[i + 1], "name": names[i]} for i in range(8)}

sections = [
    {"from": 0.0, "to": 1.3, "feel": "tension: filtered pad + rising arp + riser, no drums"},
    {"from": 1.3, "to": 3.5, "feel": "impact at 1.3 (first word), then pad + sub bass pulse + soft kick, sparse"},
    {"from": 3.5, "to": 9.5, "feel": "groove A: 4-on-floor kick, offbeat hats, bass, plucky arp, pad"},
    {"from": 9.5, "to": 15.0, "feel": "groove A + clap on 2&4, arp brighter (numbers counting)"},
    {"from": 15.0, "to": 20.5, "feel": "half-energy: kick at low level, airy arp, wide pad, riser building 18.5->20.5"},
    {"from": 20.5, "to": 28.75, "feel": "groove B: full energy, clap, 16th hats, brighter lead arp, bass syncopation (light, optimistic section)"},
    {"from": 28.75, "to": 31.5, "feel": "drop: heavy kick + 3 stabs on the three words (see slam cues)"},
    {"from": 31.5, "to": 38.5, "feel": "driving groove, arp moving, tension rising, riser 37.0->38.5"},
    {"from": 38.5, "to": 39.0, "feel": "short break / reverse swell into the logo"},
    {"from": 39.0, "to": 48.0, "feel": "big impact at 39.0, uplifting resolved chord bloom, sparkling arp, no kick after ~41.5, long tail, fade to silence by 48.0"},
]

sfx = []
for c, ln in zip(CUTS, [0.5, 0.5, 0.5, 1.0, 0.6, 0.5, 0.8]):
    sfx.append({"type": "whoosh_in", "t": c, "len": ln})
sfx += [
    {"type": "hit", "t": 1.3},
    {"type": "hit", "t": 20.5},
    {"type": "hit", "t": 28.75},
    {"type": "hit", "t": 39.0, "big": True},
    {"type": "slam", "t": vw("potencia")},
    {"type": "slam", "t": vw("integra", 1)},
    {"type": "slam", "t": vw("orquesta", 1)},
]
for s, d, r in [(vw("veinte"), 0.8, 18), (vw("ochocientos"), 1.0, 18), (vw("mas", 0), 0.75, 18), (vw("activos") + 0.1, 0.7, 18)]:
    sfx.append({"type": "tick_run", "from": s, "to": round(s + d, 3), "rate": r})
pops = [vw("atmira", 0), vw("banca"), vw("seguros"), vw("tecnologia"), vw("activos") + 0.1,
        vw("siete"), vw("sede") + 0.2, vw("orquesta", 0), vw("ciclo"), vw("completo"),
        vw("sirec", 1), vw("integra", 0), vw("inteligencia")]
for t in pops:
    sfx.append({"type": "pop", "t": round(t, 3)})
for t in [vw("europa"), vw("latinoamerica"), vw("seguridad"), vw("cumplimiento"), vw("gestion"), vw("pruebas"), vw("soporte")]:
    sfx.append({"type": "ping", "t": round(t, 3)})
for i in range(8):
    sfx.append({"type": "pop", "t": round(32.4 + i * 0.2, 3)})
sfx += [
    {"type": "shimmer", "t": round(vw("sirec", 0) - 0.1, 3)},
    {"type": "shimmer", "t": vw("atmira", 1), "big": True},
    {"type": "sparkle", "t": vw("aceleramos", 1)},
    {"type": "sparkle", "t": round(vwe("financieros", 1), 3)},
]
sfx.sort(key=lambda e: e.get("t", e.get("from", 0)))

out = {
    "fps": 30, "duration": 48, "offset": OFFSET, "bpm": 120,
    "note": "GENERATED by scripts/build-timing.py from src/data/words.json. All times are GLOBAL seconds in the final video. The VO file starts at `offset`. 120 BPM => beat 0.5 s.",
    "vo": {"file": "public/audio/vo_v2_a.mp3", "startsAt": OFFSET, "endsAt": VO_END},
    "cuts": CUTS, "scenes": scenes, "sections": sections, "sfx": sfx,
}
(ROOT / "src/data/timing.json").write_text(json.dumps(out, indent=2, ensure_ascii=False))
print("VO ends", VO_END)
for k, v in [("Los", vw("los")), ("Atmira", vw("atmira", 0)), ("veinte", vw("veinte")), ("europa", vw("europa")), ("sirec#0", vw("sirec", 0)),
             ("potencia", vw("potencia")), ("integra#1", vw("integra", 1)), ("orquesta#1", vw("orquesta", 1)), ("consultoria", vw("consultoria")),
             ("Atmira#1", vw("atmira", 1)), ("financieros#1", vwe("financieros", 1))]:
    print(f"{k:14s} {v}")
