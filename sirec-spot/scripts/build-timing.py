"""Builds src/data/timing.json (shots, music sections, SFX cues) from the Scribe word timestamps (src/data/words.json).
Single source of truth for the visuals (src/timing.ts mirrors the same lookups) and for gen-audio.py.
Cuts are placed at the centre of the natural silence between phrases."""
import json, re, unicodedata, pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
OFFSET = 1.6          # seconds of water/light before the voice starts
HOLD = 6.9            # logo hold after the last word
words = json.loads((ROOT / "src/data/words.json").read_text())

def norm(s):
    s = unicodedata.normalize("NFD", s.lower())
    s = "".join(c for c in s if unicodedata.category(c) != "Mn")
    return re.sub(r"[^a-z0-9+]", "", s)

for w in words:
    w["n"] = norm(w["text"])

def idx(text, nth=0):
    seen = 0
    for i, w in enumerate(words):
        if w["n"] == norm(text):
            if seen == nth:
                return i
            seen += 1
    raise KeyError(f"{text}#{nth}")

def vw(text, nth=0, rel=0):  return round(words[idx(text, nth) + rel]["start"] + OFFSET, 3)
def vwe(text, nth=0, rel=0): return round(words[idx(text, nth) + rel]["end"] + OFFSET, 3)
def gap(text, nth=0):
    i = idx(text, nth)
    return round((words[i]["end"] + words[i + 1]["start"]) / 2 + OFFSET, 3)

VO_END = vwe(words[-1]["text"].strip(".,"), 0) if False else round(words[-1]["end"] + OFFSET, 3)
DURATION = round(VO_END + HOLD, 2)

cuts = [gap("detiene"), gap("camino"), gap("ciclo"), gap("volver"), gap("anticiparse"), gap("riesgo"), gap("paso"),
        gap("inteligencia"), gap("corriente", 1), gap("cumplimiento"), gap("sirec", 1)]
bounds = [0.0] + cuts + [DURATION]
files = ["s01_light_rays", "s02_river_rocks", "s03_rain_ripples", "s04_river_aerial", "s05_wave_crash", "s06_horizon",
         "s07_dolphins", "s08_wave_sand", "s09_fish_school", "s10_jellyfish", "s11_ocean_aerial", "s12_sunrise"]
shots = [{"src": f + ".mp4", "from": bounds[i], "to": bounds[i + 1]} for i, f in enumerate(files)]

c = {k: v for k, v in zip(["a", "b", "c", "d", "e", "f", "g", "h", "i", "j", "k"], cuts)}
sections = [
    {"from": 0.0, "to": OFFSET, "feel": "water ambience + a single soft piano note, pad swelling in, no drums"},
    {"from": OFFSET, "to": c["b"], "feel": "gentle piano motif + warm pad + sub, very sparse, spacious reverb, light water textures"},
    {"from": c["b"], "to": c["d"], "feel": "emotional build: soft heartbeat pulse + sustained strings, piano arpeggio; credit-cycle ring (nace / fluye / vuelve)"},
    {"from": c["d"], "to": c["e"], "feel": "tension: low rumble, darker strings, rising riser into the next cut (the current gets complicated)"},
    {"from": c["e"], "to": c["h"], "feel": "rhythmic piano ostinato, strings climbing, three accent hits on the words anticipar / acompañar / recuperar (see `hit` cues)"},
    {"from": c["h"], "to": c["j"], "feel": "uplift: drums enter softly, bright arps, string melody, major resolution (SIREC reveal at the cut)"},
    {"from": c["j"], "to": c["k"], "feel": "full emotional energy, soaring strings, driving but warm; riser into the final cut"},
    {"from": c["k"], "to": DURATION, "feel": "big bloom at the cut (final logo), then calm resolution, shimmering water-like chimes, long tail, fade to true silence at the end"},
]

sfx = []
for t in [c["d"], c["e"], c["h"], c["j"], c["k"]]:
    sfx.append({"type": "whoosh_in", "t": t, "len": 0.9 if t != c["k"] else 1.4})
sfx.append({"type": "bubbles", "t": 0.2})
sfx.append({"type": "drop", "t": vw("nace")})
sfx.append({"type": "drop", "t": vw("fluye")})
sfx.append({"type": "drop", "t": vw("volver")})
for w in ["anticipar", "acompanar", "recuperar"]:
    sfx.append({"type": "hit", "t": vw(w)})
sfx.append({"type": "hit", "t": vw("sirec", 0)})
sfx.append({"type": "shimmer", "t": vw("sirec", 0)})
for w in ["propios", "terceros", "orquestados", "seguros", "cumplimiento"]:
    sfx.append({"type": "ping", "t": vw(w)})
sfx.append({"type": "tick_run", "from": vw("quince"), "to": round(vw("quince") + 0.7, 3), "rate": 16})
sfx.append({"type": "ping", "t": vw("europa")})
sfx.append({"type": "ping", "t": vw("latinoamerica")})
sfx.append({"type": "hit", "t": c["k"], "big": True})
sfx.append({"type": "ripple", "t": vw("sirec", 2), "big": True})
sfx.append({"type": "sparkle", "t": vw("fluya")})
sfx.sort(key=lambda e: e.get("t", e.get("from", 0)))

out = {
    "fps": 30, "duration": DURATION, "offset": OFFSET,
    "note": "GENERATED by scripts/build-timing.py from src/data/words.json. All times are GLOBAL seconds in the final video; the VO starts at `offset`. No fixed tempo: cut/hit times come from the narration.",
    "vo": {"file": "public/audio/vo_a.mp3", "startsAt": OFFSET, "endsAt": VO_END},
    "cuts": cuts, "shots": shots, "sections": sections, "sfx": sfx,
}
(ROOT / "src/data/timing.json").write_text(json.dumps(out, indent=2, ensure_ascii=False))
print("duration", DURATION, "VO end", VO_END)
for s in shots: print(f"{s['src']:26s} {s['from']:6.2f} -> {s['to']:6.2f}  ({s['to']-s['from']:.2f}s)")
